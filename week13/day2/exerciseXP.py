"""# Exercise 1: Implement `LoRALayer`

Create the low-rank matrices `A` and `B`, scale them with `alpha`, and test the module on a toy tensor.
"""

class LoRALayer(nn.Module):
    def __init__(self, in_dim, out_dim, rank, alpha):
        super().__init__()
        std_dev = 1 / torch.sqrt(torch.tensor(rank).float())
        self.A = nn.Parameter(torch.randn(in_dim, rank) * std_dev)
        self.B = nn.Parameter(torch.zeros(rank, out_dim))
        self.alpha = alpha
        self.rank = rank  # Store rank as an instance variable

    def forward(self, x):
        # Corrected: Access self.rank directly
        x = x @ self.A @ self.B * (self.alpha / self.rank)  # apply the low-rank update (batch, in_dim) -> (batch, out_dim)
        return x


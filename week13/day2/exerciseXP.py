"""# Exercise 4: Merged-weight LoRA layer

Fuse the LoRA matrices with the frozen weights to create a drop-in linear layer that behaves exactly like `LinearWithLoRA`.
"""

class LinearWithLoRAMerged(nn.Module):
    def __init__(self, linear, rank, alpha):
        super().__init__()
        self.linear = linear
        self.lora = LoRALayer(
            linear.in_features,
            linear.out_features,
            rank,
            alpha,
        )

    def forward(self, x):
        lora_correction = self.lora.A @ self.lora.B * (self.lora.alpha / self.lora.rank)
        combined_weight = self.linear.weight.T + lora_correction # merge original weights + scaled LoRA correction
        return F.linear(x, combined_weight.T, self.linear.bias)

